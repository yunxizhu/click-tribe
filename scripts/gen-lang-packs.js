const outDir = path.join(__dirname, '..', 'config', 'lang');
fs.mkdirSync(outDir, { recursive: true });

function emit(id, obj) {
  const zhKeys = Object.keys(zh).filter((k) => k !== 'meta').sort();
  const missing = zhKeys.filter((k) => !(k in obj));
  const extra = Object.keys(obj).filter((k) => k !== 'meta' && !(k in zh));
  if (missing.length || extra.length) {
    throw new Error(`${id} key mismatch missing=${missing} extra=${extra}`);
  }
  const body = [
    'window.TRIBE_LOCALES = window.TRIBE_LOCALES || {};',
    `window.TRIBE_LOCALES[${JSON.stringify(id)}] = ${JSON.stringify(obj, null, 2)};`,
    '',
  ].join('\n');
  const file = path.join(outDir, `${id}.js`);
  fs.writeFileSync(file, body, 'utf8');
  console.log('wrote', file);
}

emit('zh-CN', zh);
emit('en', en);
emit('ja', ja);
